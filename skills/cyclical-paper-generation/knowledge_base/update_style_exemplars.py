# ★v5.1新增：学者文风提取器（Scholar Voice Extractor）
# 从数据库学者论文中自动提取文风特征，输出 markdown 片段供人工审核后合并
# 详见同目录 scholar_voice_extractor.md
# ============================================================

def extract_scholar_voice(scholar_name: str, output_path: str = None) -> str:
    """★v5.1新增：从数据库学者论文中提取文风特征，输出 markdown 片段供人工审核后合并。

    Args:
        scholar_name: 学者姓名（如"周葆华""邓绍根"）
        output_path: 输出文件路径（可选，默认仅返回字符串）

    Returns:
        markdown 格式的学者文风特征片段
    """
    import os
    import re
    from pathlib import Path

    db_path = Path(r"c:\Users\13067\.trae-cn\数据库\论文")
    if not db_path.exists():
        return f"错误：数据库目录不存在 {db_path}"

    scholar_papers = []
    for md_file in db_path.glob(f"*_{scholar_name}.md"):
        scholar_papers.append(md_file)

    if not scholar_papers:
        return f"未找到学者 {scholar_name} 的论文"

    sections = {
        "abstract": [],
        "introduction": [],
        "literature_review": [],
        "findings": [],
        "conclusion": [],
    }

    for paper_path in scholar_papers[:5]:
        try:
            content = paper_path.read_text(encoding="utf-8")
        except Exception:
            continue

        abstract_match = re.search(r"(?:摘要|内容摘要)[：:]\s*([^\n#]{100,500})", content)
        if abstract_match:
            sections["abstract"].append({
                "paper": paper_path.stem,
                "text": abstract_match.group(1).strip()[:300]
            })

        intro_match = re.search(r"(?:一、引言|一、绪论|一、导言|## 引言|## 一、引言)[\s\n]*([^\n#]{200,800})", content)
        if intro_match:
            sections["introduction"].append({
                "paper": paper_path.stem,
                "text": intro_match.group(1).strip()[:300]
            })

        lit_match = re.search(r"(?:二、文献综述|## 文献综述|文献回顾)[\s\n]*([^\n#]{200,800})", content)
        if lit_match:
            sections["literature_review"].append({
                "paper": paper_path.stem,
                "text": lit_match.group(1).strip()[:300]
            })

        find_match = re.search(r"(?:三、研究[发结]|## 研究发现|四、研究[发结])[\s\n]*([^\n#]{200,800})", content)
        if find_match:
            sections["findings"].append({
                "paper": paper_path.stem,
                "text": find_match.group(1).strip()[:300]
            })

        concl_match = re.search(r"(?:[五五六六七]、结语|## 结语|结论)[\s\n]*([^\n#]{200,800})", content)
        if concl_match:
            sections["conclusion"].append({
                "paper": paper_path.stem,
                "text": concl_match.group(1).strip()[:300]
            })

    all_text = ""
    for sec in sections.values():
        for item in sec:
            all_text += item["text"]

    sentences = [s.strip() for s in re.split(r'[。！？]', all_text) if len(s.strip()) > 5]
    if len(sentences) >= 5:
        lengths = [len(s) for s in sentences]
        mean_len = sum(lengths) / len(lengths)
        variance = sum((l - mean_len) ** 2 for l in lengths) / len(lengths)
    else:
        variance = 0.0

    md = f"# {scholar_name} 文风特征提取报告\n\n"
    md += f"> 来源：数据库 `c:\\Users\\13067\\.trae-cn\\数据库\\论文\\` 中 {scholar_name} 代表论文\n"
    md += f"> 处理论文数：{len(scholar_papers)} 篇\n"
    md += f"> 句长方差：{variance:.2f}\n\n"

    section_labels = {
        "abstract": "摘要范本",
        "introduction": "引言范本",
        "literature_review": "文献综述范本",
        "findings": "发现范本",
        "conclusion": "结语范本",
    }

    for sec_key, sec_label in section_labels.items():
        md += f"## {sec_label}\n\n"
        if sections[sec_key]:
            for item in sections[sec_key][:2]:
                md += f"> 来源：《{item['paper']}》\n\n"
                md += f"{item['text']}\n\n"
        else:
            md += "（未提取到该章节内容）\n\n"

    pinyin_map = {
        "周葆华": "zhou",
        "邓绍根": "deng",
        "刘战伟": "liu",
        "黄阳坤": "huang",
        "雷紫雯": "lei",
    }
    pinyin = pinyin_map.get(scholar_name, scholar_name[0])
    md += f"## 建议 VOICE_SAMPLES 子键名\n\n"
    md += f"基于学者研究方向，建议子键名：`<research_type>_{pinyin}`\n"
    md += f"例如：`computational_{pinyin}`、`theoretical_{pinyin}`\n\n"
    md += f"## 人工审核要点\n\n"
    md += f"1. 确认摘录为原文（未修改）\n"
    md += f"2. 确认摘录具有该学者文风代表性\n"
    md += f"3. 确认摘录不含违规表达\n"
    md += f"4. 确认 VOICE_SAMPLES 子键名遵循命名规范\n"

    if output_path:
        Path(output_path).write_text(md, encoding="utf-8")
        return f"已输出至 {output_path}"

    return md


