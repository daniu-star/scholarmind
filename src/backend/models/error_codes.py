"""
ScholarMind 结构化错误码
统一错误响应格式，便于前端精确处理各类异常
"""
from __future__ import annotations

from enum import Enum


class ErrorCode(str, Enum):
    """结构化业务错误码"""

    # ── 通用错误 ──
    INTERNAL_ERROR = "INTERNAL_ERROR"
    VALIDATION_ERROR = "VALIDATION_ERROR"
    NOT_FOUND = "NOT_FOUND"
    RATE_LIMITED = "RATE_LIMITED"
    PERMISSION_DENIED = "PERMISSION_DENIED"
    AUTHENTICATION_FAILED = "AUTHENTICATION_FAILED"
    PAYMENT_REQUIRED = "PAYMENT_REQUIRED"
    CHAT_QUOTA_EXHAUSTED = "CHAT_QUOTA_EXHAUSTED"

    # ── Agent 相关 ──
    AGENT_NOT_FOUND = "AGENT_NOT_FOUND"
    AGENT_CHAT_FAILED = "AGENT_CHAT_FAILED"
    AGENT_STREAM_FAILED = "AGENT_STREAM_FAILED"
    SESSION_NOT_FOUND = "SESSION_NOT_FOUND"
    INVALID_AGENT_ID = "INVALID_AGENT_ID"

    # ── CNKI 知识库 ──
    CNKI_SEARCH_FAILED = "CNKI_SEARCH_FAILED"
    CNKI_CONNECTION_FAILED = "CNKI_CONNECTION_FAILED"
    CNKI_PARSE_FAILED = "CNKI_PARSE_FAILED"

    # ── 图表生成 ──
    CHART_GENERATION_FAILED = "CHART_GENERATION_FAILED"
    INVALID_CHART_TYPE = "INVALID_CHART_TYPE"
    CHART_NOT_FOUND = "CHART_NOT_FOUND"

    # ── 文件上传 ──
    FILE_TOO_LARGE = "FILE_TOO_LARGE"
    INVALID_FILE_TYPE = "INVALID_FILE_TYPE"
    UPLOAD_FAILED = "UPLOAD_FAILED"
    FILE_NOT_FOUND = "FILE_NOT_FOUND"

    # ── 技能管理 ──
    SKILL_NOT_FOUND = "SKILL_NOT_FOUND"
    SKILL_ALREADY_EXISTS = "SKILL_ALREADY_EXISTS"
    SKILL_VALIDATION_FAILED = "SKILL_VALIDATION_FAILED"
    SKILL_CREATE_FAILED = "SKILL_CREATE_FAILED"

    # ── 数据库 ──
    DB_CONNECTION_FAILED = "DB_CONNECTION_FAILED"
    DB_MIGRATION_FAILED = "DB_MIGRATION_FAILED"

    # ── 外部服务 ──
    EXTERNAL_SERVICE_ERROR = "EXTERNAL_SERVICE_ERROR"
    LLM_API_FAILED = "LLM_API_FAILED"

    # ── Pipeline 相关 ──
    PIPELINE_CONCURRENCY_FULL = "PIPELINE_CONCURRENCY_FULL"
