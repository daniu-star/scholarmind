def detect_intra_paragraph_disconnect_gen(text: str) -> Dict:
    """★v5.0新增：检测段内首句-第二句断裂（generation pipeline 简化版）

    简化判定：首句极短（<15字）且第二句极长（>50字）视为潜在断裂。
    """
    import re
    paragraphs = [p.strip() for p in text.split('\n') if p.strip()]
    severe_breaks = 0
    potential_breaks = 0
    for p in paragraphs:
        sentences = [s.strip() for s in re.split(r'[。！？]', p) if s.strip()]
        if len(sentences) >= 2:
            first_len = len(sentences[0])
            second_len = len(sentences[1])
            if first_len < 15 and second_len > 50:
                potential_breaks += 1
    passed = severe_breaks == 0
    return {
        "passed": passed,
        "potential_disconnects": potential_breaks,
        "severe_disconnects": severe_breaks,
        "desc": f"段内断裂检测: 潜在={potential_breaks}, 严重={severe_breaks}",
    }


def detect_paragraph_transition_quality_gen(text: str) -> Dict:
    """★v5.0新增：检测段间过渡质量（generation pipeline 版）

    基于数据库C刊论文实证，机械连接词占段间过渡总数的比例：
        - 正常占比 <15%
        - 触发修复阈值 >15%（★v5.0校准，与 review pipeline 对齐）
    """
    paragraphs = [p.strip() for p in text.split('\n') if p.strip()]
    if len(paragraphs) <= 1:
        return {"passed": True, "mechanical_ratio": 0.0, "violations": [], "desc": "段间过渡: 段落数不足"}
    subsequent = paragraphs[1:]
    total_transitions = len(subsequent)
    mechanical_words = ["首先", "其次", "再次", "最后", "第一", "第二", "第三",
                        "一方面", "另一方面", "综上所述", "总而言之", "总的来说",
                        "如上所述"]
    mechanical_count = 0
    for p in subsequent:
        head = p[:30]
        if any(w in head for w in mechanical_words):
            mechanical_count += 1
    mechanical_ratio = mechanical_count / total_transitions if total_transitions > 0 else 0.0
    # ★v5.0：阈值 0.15（与 review pipeline 修改 3 对齐）
    passed = mechanical_ratio <= 0.15
    violations = []
    if not passed:
        violations.append(f"机械连接词占比 {mechanical_ratio:.1%} 超过阈值 15%")
    return {
        "passed": passed,
        "mechanical_count": mechanical_count,
        "total_transitions": total_transitions,
        "mechanical_ratio": mechanical_ratio,
        "violations": violations,
        "desc": f"段间过渡质量: 机械={mechanical_count}/{total_transitions}（{mechanical_ratio:.1%}）",
    }


