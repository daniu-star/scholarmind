def check_rhythm(text: str) -> Dict:
    """检查句子节奏（句长方差）—— 检测僵硬化与散文化"""
    import re
    sentences = [s.strip() for s in re.split(r'[。！？]', text) if len(s.strip()) > 5]
    if len(sentences) < 5:
        return {"variance": 0, "mean_length": 0, "too_uniform": False,
                "too_jumpy": False, "passed": True, "note": "句子数不足"}
    lengths = [len(s) for s in sentences]
    mean = sum(lengths) / len(lengths)
    variance = sum((l - mean) ** 2 for l in lengths) / len(lengths)
    too_uniform = variance < RHYTHM_METRICS["sentence_length_variance_min"]
    too_jumpy = variance > RHYTHM_METRICS["sentence_length_variance_max"]
    return {
        "variance": round(variance, 1),
        "mean_length": round(mean, 1),
        "too_uniform": too_uniform,  # 僵硬化信号
        "too_jumpy": too_jumpy,  # 散文化信号
        "passed": not (too_uniform or too_jumpy),
    }


def check_paragraph_opening_diversity(text: str) -> Dict:
    """检查段落开头多样性 —— 检测机械式开头"""
    paragraphs = [p.strip() for p in text.split("\n\n") if len(p.strip()) > 50]
    if len(paragraphs) < 5:
        return {"diversity": 1.0, "unique_openings": 0, "total_paragraphs": len(paragraphs),
                "max_consecutive_connector": 0, "passed": True, "note": "段落数不足"}
    openings = [p[:6] for p in paragraphs]  # 取前6字符
    unique = len(set(openings))
    diversity = unique / len(openings)
    # 检测连续相同连接词
    connectors = ["然而", "此外", "同时", "另外", "首先", "其次", "因此", "综上", "进而", "更进一步"]
    consecutive = 0
    max_consecutive = 0
    last_connector = None
    for p in paragraphs:
        first_word = p[:2]
        if first_word in connectors:
            if first_word == last_connector:
                consecutive += 1
                max_consecutive = max(max_consecutive, consecutive)
            else:
                consecutive = 1
                last_connector = first_word
        else:
            consecutive = 0
            last_connector = None
    return {
        "diversity": round(diversity, 2),
        "unique_openings": unique,
        "total_paragraphs": len(paragraphs),
        "max_consecutive_connector": max_consecutive,
        "passed": diversity >= RHYTHM_METRICS["paragraph_opening_diversity_min"]
                  and max_consecutive <= RHYTHM_METRICS["max_consecutive_same_connector"],
    }


def check_mechanical_patterns(text: str) -> Dict:
    """检测机械式模式（断裂式罗列、模板化套话）"""
    import re
    mechanical = []
    # 断裂式罗列
    if re.search(r'第一[，,].*第二[，,].*第三', text, re.DOTALL):
        mechanical.append("断裂式罗列（第一/第二/第三）")
    if re.search(r'首先[，,].*其次[，,].*再次', text, re.DOTALL):
        mechanical.append("断裂式罗列（首先/其次/再次）")
    if re.search(r'一方面[，,].*另一方面[，,]', text, re.DOTALL):
        mechanical.append("断裂式罗列（一方面/另一方面）")
    # 模板化套话
