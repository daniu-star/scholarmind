    parts.append(f"破折号≤{g['max_dash_count']}处，分号≤{g['max_semicolon_count']}处")
    parts.append(f"禁止断裂式表达，禁止空洞修饰语")

    # 按 agent 类型添加特定约束
    if agent_type in ["polisher"]:
        for section, rules in STYLE_RULES.items():
            if section == "global":
                continue
            if isinstance(rules, dict) and "words" in rules:
                parts.append(f"    {rules.get('structure_label', section)}: {rules['words']}字")
            if "forbidden" in rules:
                parts.append(f"    禁止: {', '.join(rules['forbidden'])}")

    if agent_type in ["expert"]:
        parts.append(f"研究方法章节必须包含: {', '.join(g['forbidden_citation_patterns'])}")
        parts.append(f"建议补充 ≥8 条 CSSCI 期刊中文文献")

    if agent_type in ["word_count_controller"]:
        for section, rules in STYLE_RULES.items():
            if section in ["title", "global"]:
                continue
            if isinstance(rules, dict) and "words" in rules:
                w_range = f"{rules.get('min_words', '')}-{rules.get('max_words', rules['words'])}"
                parts.append(f"    {section}: {w_range}字")

    # v6.1 新增：注入正向句式模式（声音优先）
    patterns = RECOMMENDED_PATTERNS.get(research_type, RECOMMENDED_PATTERNS["qualitative"])
    parts.append(f"\n【推荐句式模式 - {research_type}】")
