def check_dash_count(text: str, max_count: int = 15) -> tuple:
    """检查破折号数量"""
    count = text.count("——")
    return (count, count > max_count, f"破折号: {count}/{max_count}")


def check_word_count(text: str, max_words: int = 15000, tolerance: float = 0.10) -> tuple:
    """检查全文字数"""
    # 中文字数 = 去掉空白符后的字符数
    count = len(text.replace(" ", "").replace("\n", "").replace("\r", ""))
    limit = int(max_words * (1 + tolerance))
    return (count, count > limit, f"全文字数: {count}/{max_words} (上限{limit})")


def check_chinese_word_count(text: str) -> int:
    """计算中文字数（去除空白符和标点符号的纯中文字符数）"""
    import re
    chinese_chars = re.findall(r'[一-鿿]', text)
    return len(chinese_chars)


def check_forbidden_patterns(text: str, patterns: List[str]) -> list:
    """检查禁止的断裂式表达"""
    import re
    violations = []
    for pattern in patterns:
        matches = re.findall(pattern, text)
        if matches:
            violations.append(f"发现禁止模式 '{pattern}': {len(matches)} 处")
    return violations


def check_forbidden_phrases(text: str, phrases: List[str]) -> list:
    """检查禁止的空洞修饰语"""
    violations = []
    for phrase in phrases:
        count = text.count(phrase)
        if count > 0:
            violations.append(f"禁止用语 '{phrase}': {count} 处")
    return violations


def check_sentence_lengths(text: str, max_words: int = 60) -> tuple:
    """检查句长（按句号分句）"""
    import re
    sentences = re.split(r'[。！？；]', text)
    long_sentences = [s for s in sentences if len(s) > max_words]
    return (len(long_sentences), long_sentences[:5])


def check_paragraph_lengths(text: str, max_words: int = 400, min_words: int = 100) -> dict:
    """检查段落长度"""
    paragraphs = [p for p in text.split("\n\n") if len(p.strip()) > 0]
    too_long = [p for p in paragraphs if len(p) > max_words]
    too_short = [p for p in paragraphs if 0 < len(p) < min_words and len(p) > 10]
    return {
        "total_paragraphs": len(paragraphs),
        "too_long": len(too_long),
        "too_short": len(too_short),
        "long_paragraphs": [p[:50] + "..." for p in too_long[:3]],
        "short_paragraphs": [p[:50] + "..." for p in too_short[:3]],
    }


def check_colon_density(text: str, max_per_1000_words: int = 2) -> tuple:
    """检查冒号密度"""
    colon_count = text.count("：")  # 全角冒号
    total_chars = len(text.replace(" ", "").replace("\n", ""))
    # 每千字密度
    if total_chars > 0:
        density = colon_count / (total_chars / 1000)
    else:
        density = 0
    return (colon_count, density > max_per_1000_words,
            f"冒号: {colon_count}处 ({density:.1f}/千字, 上限{max_per_1000_words})")


