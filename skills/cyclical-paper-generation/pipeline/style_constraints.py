def check_human_language_compliance(text: str, discipline: str = "communication") -> Dict[str, Any]:
    """★v7.2 新增：人类语言合规检查函数

    基于 knowledge_base/human_language_features.md 第六章的强制合规检查标准。
    执行微观、中观、宏观、人味四层合规检查。

    Args:
        text: 待检查的论文文本
        discipline: 学科类型（communication/economics/law/ethnology/cultural_studies）

    Returns:
        检查结果字典，包含：
        - passed: 是否通过
        - failed_checks: 未通过项列表
        - suggestions: 修复建议
        - details: 详细检查结果
    """
    import re
    import statistics

    result = {
        "passed": True,
        "failed_checks": [],
        "suggestions": [],
        "details": {}
    }

    # === 微观层面检查 ===

    # 6.1.1 句长方差检查
    sentences = re.split(r'[。！？]', text)
    sentences = [s.strip() for s in sentences if s.strip()]
    if len(sentences) >= 5:
        sentence_lengths = [len(s) for s in sentences]
        std = statistics.stdev(sentence_lengths) if len(sentence_lengths) > 1 else 0
        result["details"]["sentence_length_std"] = round(std, 2)
        if std < HUMAN_LANGUAGE_THRESHOLDS["sentence_length_std_min"]:
            result["passed"] = False
            result["failed_checks"].append("sentence_length_std")
            result["suggestions"].append(
                f"句长标准差({std:.2f})低于阈值({HUMAN_LANGUAGE_THRESHOLDS['sentence_length_std_min']})，"
                f"需增加长短句交错，提高句长方差"
            )

    # 6.1.2 段落开头多样性检查
    paragraphs = [p.strip() for p in text.split('\n') if p.strip()]
    if len(paragraphs) >= 3:
        openings = set()
        for p in paragraphs:
            # 提取前4个字符作为开头类型
            opening = p[:4] if len(p) >= 4 else p
            openings.add(opening)
        result["details"]["paragraph_opening_types"] = len(openings)
        if len(openings) < HUMAN_LANGUAGE_THRESHOLDS["paragraph_opening_types_min"]:
            result["passed"] = False
            result["failed_checks"].append("paragraph_opening_diversity")
            result["suggestions"].append(
                f"段落开头类型({len(openings)})少于阈值({HUMAN_LANGUAGE_THRESHOLDS['paragraph_opening_types_min']})，"
                f"需多样化段落开头方式"
            )

    # 6.1.3 AI高频词检测
    text_length = len(text)
    thousand_words = max(text_length / 1000, 1)
    ai_phrase_violations = []

    for phrase, threshold in HUMAN_LANGUAGE_THRESHOLDS["ai_phrase_thresholds"].items():
        count = text.count(phrase)
        if threshold == 0 and count > 0:
            ai_phrase_violations.append(f"'{phrase}'禁止使用，发现{count}次")
        elif count / thousand_words > threshold:
            ai_phrase_violations.append(
                f"'{phrase}'超阈值：{count}次/{thousand_words:.1f}千字（阈值{threshold}次/千字）"
            )

    # 检查禁止的段落开头
    for opening in HUMAN_LANGUAGE_THRESHOLDS["forbidden_paragraph_openings"]:
        for p in paragraphs:
            if p.startswith(opening):
                ai_phrase_violations.append(f"段落以'{opening}'开头（禁止）")
                break

    # 检查段落开头连接词限制
    for connector, limit in HUMAN_LANGUAGE_THRESHOLDS["paragraph_opening_connector_limits"].items():
        count = sum(1 for p in paragraphs if p.startswith(connector))
        if count > limit:
            ai_phrase_violations.append(
                f"'{connector}'作为段落开头{count}次（上限{limit}次）"
            )

    if ai_phrase_violations:
        result["passed"] = False
        result["failed_checks"].append("ai_phrase_detection")
        result["suggestions"].extend(ai_phrase_violations)

    result["details"]["ai_phrase_violations"] = ai_phrase_violations

    # 6.1.4 短句收束检查
    short_ending_count = 0
    for p in paragraphs:
        if not p:
            continue
        # 获取段落最后一句
        last_sentence_match = re.findall(r'[^。！？]*[。！？]', p)
        if last_sentence_match:
            last_sentence = last_sentence_match[-1].rstrip('。！？')
            if len(last_sentence) <= HUMAN_LANGUAGE_THRESHOLDS["short_ending_max_words"]:
                short_ending_count += 1

    result["details"]["short_ending_count"] = short_ending_count
    result["details"]["total_paragraphs"] = len(paragraphs)

    # === 宏观层面检查 ===

    # 6.3.3 作者声音检查
    author_voice_found = False
    for marker in HUMAN_LANGUAGE_THRESHOLDS["author_voice_markers"]:
        if marker in text:
            author_voice_found = True
            break

    result["details"]["author_voice_found"] = author_voice_found
    if not author_voice_found:
        result["passed"] = False
        result["failed_checks"].append("author_voice")
        result["suggestions"].append(
            "未检测到作者声音标记（'我们'/'本文'/'笔者'），需添加作者判断句"
        )

    # 6.3.2 过渡方式检查（检测机械连接词）
    mechanical_connectors = ["此外", "另外", "同时", "除此之外"]
    mechanical_count = 0
    for p in paragraphs:
        for connector in mechanical_connectors:
            if p.startswith(connector):
                mechanical_count += 1

    result["details"]["mechanical_connector_count"] = mechanical_count
    if mechanical_count > 2:
        result["passed"] = False
        result["failed_checks"].append("transition_methods")
        result["suggestions"].append(
            f"检测到{mechanical_count}处机械连接词段落开头，"
            f"需改为语义衔接型过渡（概念锚定/经验切入/理论对话/转折推进/递进深化）"
        )

    # === 综合判定 ===
    result["details"]["discipline"] = discipline
    result["details"]["check_version"] = "v7.2"

    if not result["passed"]:
        result["suggestions"].insert(0, "论文未通过人类语言合规检查，需根据以下建议修复后重新检查。")

    return result
