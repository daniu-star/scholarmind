def detect_hard_transitions_gen(text: str) -> Dict:
    """★v5.0新增：检测硬切换（generation pipeline 版）

    检测相邻段落间既无过渡词又存在主题跳跃的情况。
    """
    import re
    paragraphs = [p.strip() for p in text.split('\n') if p.strip()]
    if len(paragraphs) <= 1:
        return {"passed": True, "hard_switches": 0, "desc": "硬切换检测: 段落数不足"}
    title_pattern = re.compile(r"^[一二三四五六七八九十]+、|^（[一二三四五六七八九十]+）|^[\d]+[.．]")
    transition_words = ["然而", "与之相对", "在这一基础上", "更深一层看", "伴随着",
                        "进一步而言", "与此相应", "问题在于", "回到本研究", "换言之",
                        "由此", "从这一视角出发", "与此同时", "不仅如此", "更重要的是"]
    hard_switches = 0
    for p in paragraphs[1:]:
        head = p[:30]
        has_transition = any(w in head for w in transition_words)
        if not has_transition and title_pattern.match(p):
            hard_switches += 1
    passed = hard_switches == 0
    return {
        "passed": passed,
        "hard_switches": hard_switches,
        "desc": f"硬切换检测: {hard_switches}处{'（未通过）' if not passed else ''}",
    }


def detect_mechanical_connectors_gen(text: str) -> Dict:
    """★v5.0新增：检测机械连接词（generation pipeline 版）

    检测"首先/其次/再次/最后"等公式化过渡词。
    """
    mechanical_words = ["首先，", "其次，", "再次，", "最后，", "第一，", "第二，",
                        "第三，", "一方面，", "另一方面，", "综上所述，",
                        "总而言之，", "总的来说，", "如上所述，"]
