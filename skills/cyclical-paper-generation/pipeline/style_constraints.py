def detect_numeric_format_violations_gen(text: str) -> Dict:
    """★v5.1新增：检测数字使用规范违规（generation pipeline 版）

    规则：数据数字用阿拉伯数字，严肃数字用汉字数字。
    严肃数字语境（新中国成立、改革开放等）后若紧跟阿拉伯数字，则判定为违规。
    数据数字语境（样本量、回归系数等）后若紧跟汉字数字，则判定为违规。

    Args:
        text: 待检测文本

    Returns:
        检测结果字典
    """
    # 严肃数字语境列表（与 STYLE_RULES["global"]["numeric_formatting"]["solemn_number_contexts"] 保持一致）
    solemn_contexts = [
        "新中国成立", "改革开放", "五四运动", "辛亥革命", "建党",
        "抗战", "解放战争", "新中国成立以来", "改革开放以来",
        "建党以来", "百年", "十年", "数十年", "几个世纪", "千年",
    ]
    # 数据数字语境列表
    data_contexts = [
        "样本量", "样本数", "受访者", "被试", "问卷份数", "有效问卷",
        "回归系数", "百分比", "比例", "频次", "次数", "人次", "篇次",
    ]

    violations: List[str] = []
    violation_count = 0

    # 检测1：严肃数字语境后紧跟阿拉伯数字
    # 模式：严肃语境 + 0-5字间隔 + 阿拉伯数字 + 年/余/载 等时间单位
    for context in solemn_contexts:
        # 匹配 "新中国成立 70 年来" / "改革开放40余年" 等模式
        pattern = re.escape(context) + r"[^\d一二三四五六七八九十百千零]{0,3}(\d+)[\s]*[年余载载余]"
        matches = re.findall(pattern, text)
        for match in matches:
            violation_count += 1
            violations.append(
                f"严肃数字语境'{context}'后误用阿拉伯数字'{match}'，应改为汉字数字"
            )

    # 检测2：数据数字语境后紧跟汉字数字
    chinese_num_pattern = r"[一二三四五六七八九十百千零]+"
    for context in data_contexts:
        pattern = re.escape(context) + r"[^\d一二三四五六七八九十百千零]{0,3}(" + chinese_num_pattern + r")"
        matches = re.findall(pattern, text)
        for match in matches:
            # 排除"十余年"等纯修饰性表达
            if len(match) <= 4 and match not in ["十余", "数余", "若干"]:
                violation_count += 1
                violations.append(
                    f"数据数字语境'{context}'后误用汉字数字'{match}'，应改为阿拉伯数字"
                )

    return {
        "violation_count": violation_count,
        "violations": violations[:10],  # 限制详情数量
        "passed": violation_count == 0,
        "fix_suggestion": (
            "数据数字（样本量、回归系数、百分比等）须使用阿拉伯数字；"
            "严肃数字（新中国成立、改革开放等语境）须使用汉字数字。"
        ) if violation_count > 0 else "",
    }


