    if agent_type in ["polisher", "narrator", "architect", "expert"]:
        samples = VOICE_SAMPLES.get(research_type, {})
        if samples:
            parts.append(f"\n【目标文风尚本 - {research_type}】")
            for section, sample in samples.items():
                parts.append(f"  [{section}]")
                parts.append(f"  {sample}")

