def compute_section_budgets(target_words: int, tolerance: float = 0.10) -> Dict[str, Dict[str, int]]:
    """根据用户指定的全文字数目标，按比例计算各章节字数预算（v6.3新增）

    核心逻辑：以 STYLE_RULES 中各章节的默认字数比例为基准，按用户目标
    等比缩放，确保无论用户指定多少字，各章节比例不变，总字数严格受限。

    参数:
        target_words: 用户指定的全文字数目标
        tolerance: 容差比例（默认 ±10%）

    返回:
        各章节字数预算字典，格式：
        {
            "global": {"target": 12000, "hard_limit": 13200, "soft_limit": 10800},
            "abstract": {"target": 280, "min": 252, "max": 308},
            "introduction": {"target": 480, "min": 432, "max": 528},
            ...
        }
    """
    # 基准总字数（STYLE_RULES 中各章节 words 之和）
    DEFAULT_TOTAL = 15000
    section_defaults = {}
    for section, rules in STYLE_RULES.items():
        if section in ("global", "title"):
            continue
        if isinstance(rules, dict) and "words" in rules:
            section_defaults[section] = {
                "default_words": rules["words"],
                "default_min": rules.get("min_words", int(rules["words"] * 0.9)),
                "default_max": rules.get("max_words", int(rules["words"] * 1.1)),
            }

    # 计算缩放比例
    scale = target_words / DEFAULT_TOTAL

    budgets: Dict[str, Dict[str, int]] = {}

    # 全局预算
    budgets["global"] = {
        "target": target_words,
        "hard_limit": int(target_words * (1 + tolerance)),
        "soft_limit": int(target_words * (1 - tolerance)),
    }

    # 各章节预算（等比缩放）
    for section, defaults in section_defaults.items():
        scaled_target = max(100, int(defaults["default_words"] * scale))
        scaled_min = max(50, int(defaults["default_min"] * scale))
        scaled_max = max(scaled_target, int(defaults["default_max"] * scale))
        budgets[section] = {
            "target": scaled_target,
            "min": scaled_min,
            "max": scaled_max,
        }

    return budgets


def build_word_budget_constraint(target_words: int, current_words: int,
                                 section_words: Dict[str, int] = None,
                                 tolerance: float = 0.10) -> str:
    """构建字数预算硬约束文本，注入到每个 Agent 的 instruction 中（v6.3新增）

    核心策略：
    - 事前约束：告诉 Agent 当前剩余预算，禁止超限
    - 动态调整：根据当前实际字数与目标的差距，给出不同强度的约束
    - 硬约束语言：使用"禁止""不得超过"等绝对性表述

    参数:
        target_words: 用户指定的全文字数目标
        current_words: 当前论文实际字数
        section_words: 各章节当前字数（可选，用于逐节预算）
        tolerance: 容差比例

    返回:
        字数预算硬约束文本
    """
    budgets = compute_section_budgets(target_words, tolerance)
    hard_limit = budgets["global"]["hard_limit"]
    delta = current_words - target_words
    over_limit = current_words > hard_limit
    near_limit = current_words > target_words  # 超过目标但未超硬限

    parts = [
        "【字数硬约束 — 不可违反】",
        f"用户指定全文字数：{target_words}字",
        f"硬上限（含容差）：{hard_limit}字",
        f"当前全文字数：{current_words}字",
        f"与目标差距：{'超' if delta > 0 else '差'}{abs(delta)}字",
    ]

    # 各章节预算
    parts.append("\n各章节字数预算：")
    for section, budget in budgets.items():
        if section == "global":
            continue
        section_name_map = {
            "abstract": "摘要", "introduction": "引言",
            "literature_review": "文献回顾", "method": "研究方法",
            "findings": "研究发现", "conclusion": "结语",
        }
        name = section_name_map.get(section, section)
        actual = section_words.get(section, 0) if section_words else 0
        status = ""
        if actual > 0:
            if actual > budget["max"]:
                status = f" ❌ 超标({actual}字)"
            elif actual > budget["target"]:
                status = f" ⚠ 接近上限({actual}字)"
            else:
                status = f" ✅ ({actual}字)"
        parts.append(f"  {name}: 目标{budget['target']}字 ({budget['min']}-{budget['max']}){status}")

    # 根据当前状态给出约束指令
    if over_limit:
        parts.append("\n⚠⚠⚠ 严重超标！当前字数已超过硬上限！")
        parts.append("【强制指令】你只能删除内容，禁止新增任何文字。")
        parts.append("每处修改必须使总字数减少，不得增加。")
        parts.append(f"必须至少削减 {delta - int(target_words * tolerance)} 字才能回到安全范围。")
    elif near_limit:
        parts.append("\n⚠ 字数已超过目标值，接近硬上限。")
        parts.append("【约束指令】修改时优先精简，新增内容必须同时删除等量或更多文字。")
        parts.append("禁止净增字数。")
    else:
        remaining = target_words - current_words
        parts.append(f"\n字数在安全范围内，剩余预算 {remaining} 字。")
        parts.append("修改时注意控制篇幅，新增内容需在预算内。")

    return "\n".join(parts)


def check_framework_budget_compliance(
    framework_total_budget: int,
    section_budgets: Dict[str, int],
    target_words: int,
    tolerance: float = 0.05,
) -> Dict[str, Any]:
    """防线4：框架阶段字数预算校验（v5.1新增，v7.4落地实现 G22 修复）

    在 ConstraintInjector 注入阶段，强制校验 Architect 输出的框架总字数预算：
    - 若框架总字数预算 > user_target_words × (1 + tolerance)，拦截并要求 Architect 重新调整
    - 若各章节字数预算之和 > user_target_words × (1 + tolerance)，拦截并要求 Architect 重新调整
    - 此防线在每轮循环开始时执行，确保字数膨胀在源头被控制

    参数:
        framework_total_budget: Architect 输出的框架总字数预算
        section_budgets: 各章节字数预算字典，如 {"abstract": 300, "introduction": 600, ...}
        target_words: 用户指定的全文字数目标
        tolerance: 容差比例（默认 0.05，即 ±5%）

    返回:
        校验结果字典，格式：
        {
            "passed": bool,
            "total_budget": int,
            "section_sum": int,
            "hard_limit": int,
            "violations": List[str],
            "desc": str,
        }
    """
    hard_limit = int(target_words * (1 + tolerance))
    violations: List[str] = []

    # 检查1：框架总字数预算是否超限
    if framework_total_budget > hard_limit:
        violations.append(
            f"框架总字数预算 {framework_total_budget} 超过硬上限 {hard_limit}，"
            f"需 Architect 重新调整至 {target_words} 字以内"
        )

    # 检查2：各章节字数预算之和是否超限
    section_sum = sum(section_budgets.values()) if section_budgets else 0
    if section_sum > hard_limit:
        violations.append(
            f"各章节字数预算之和 {section_sum} 超过硬上限 {hard_limit}，"
            f"需 Architect 重新分配各章节预算"
        )

    # 检查3：各章节预算是否与对应默认比例严重失衡（偏差>50%视为异常）
    default_budgets = compute_section_budgets(target_words, tolerance)
    for section, budgeted in section_budgets.items():
        if section == "global":
            continue
        default_target = default_budgets.get(section, {}).get("target", 0)
        if default_target > 0:
            ratio = budgeted / default_target
            if ratio > 1.5 or ratio < 0.5:
                violations.append(
                    f"章节 {section} 预算 {budgeted} 与默认比例 {default_target} 严重失衡"
                    f"（偏差{(ratio - 1) * 100:+.0f}%），需 Architect 重新调整"
                )

    passed = len(violations) == 0
    desc = (
        f"框架预算校验: 总预算{framework_total_budget}/章节和{section_sum}/"
        f"硬上限{hard_limit}{'（通过）' if passed else '（拦截）'}"
    )

    return {
        "passed": passed,
        "total_budget": framework_total_budget,
        "section_sum": section_sum,
        "hard_limit": hard_limit,
        "violations": violations,
        "desc": desc,
    }


