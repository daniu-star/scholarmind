"""Task scheduler — generates Journal×Year×Issue tasks for all 5 disciplines.

For each journal, generates issue-level tasks for 2016-2026.
Paper-level tasks are generated by workers from issue pages.
"""

from __future__ import annotations

import asyncio
import structlog
import time
from typing import Optional

from redis.asyncio import Redis

from config.journals import get_all_journals, VALID_DISCIPLINES, JournalConfig
from models.task import Task
from models.enums import TaskStatus
from master.task_manager import TaskManager

logger = structlog.get_logger()


class TaskScheduler:
    """Generates and schedules download tasks for all journals."""

    def __init__(self, redis: Redis):
        self._redis = redis
        self._task_manager = TaskManager(redis)
        self._running = False

    async def generate_all_tasks(self, year_start: int = 2016, year_end: int = 2026) -> int:
        """Generate issue-level tasks for all journals × all years.

        Returns total number of tasks generated.
        """
        all_journals = get_all_journals()
        total = 0

        for journal in all_journals:
            for year in range(year_start, year_end + 1):
                task = Task(
                    discipline=journal.discipline,
                    journal_name=journal.name,
                    journal_url=journal.navi_url,
                    year=year,
                    issue_number="",  # Will be filled by worker from journal page
                    status=TaskStatus.PENDING,
                    max_retries=3,
                )
                await self._task_manager.enqueue(task)
                total += 1

        logger.info(
            "all_tasks_generated",
            journals=len(all_journals),
            year_range=f"{year_start}-{year_end}",
            total_tasks=total,
        )
        return total

    async def generate_discipline_tasks(
        self, discipline: str, year_start: int = 2016, year_end: int = 2026
    ) -> int:
        """Generate tasks for a single discipline."""
        from config.journals import get_journals_for

        journals = get_journals_for(discipline)
        total = 0

        for journal in journals:
            for year in range(year_start, year_end + 1):
                task = Task(
                    discipline=journal.discipline,
                    journal_name=journal.name,
                    journal_url=journal.navi_url,
                    year=year,
                    issue_number="",
                    status=TaskStatus.PENDING,
                    max_retries=3,
                )
                await self._task_manager.enqueue(task)
                total += 1

        logger.info(
            "discipline_tasks_generated",
            discipline=discipline,
            tasks=total,
        )
        return total

    async def generate_journal_tasks(
        self, journal: JournalConfig, year_start: int = 2016, year_end: int = 2026
    ) -> int:
        """Generate tasks for a specific journal."""
        total = 0

        for year in range(year_start, year_end + 1):
            task = Task(
                discipline=journal.discipline,
                journal_name=journal.name,
                journal_url=journal.navi_url,
                year=year,
                issue_number="",
                status=TaskStatus.PENDING,
                max_retries=3,
            )
            await self._task_manager.enqueue(task)
            total += 1

        return total

    async def get_scheduler_status(self) -> dict:
        """Get current scheduler state."""
        queue_sizes = await self._task_manager.get_all_queue_sizes()
        stats = await self._task_manager.get_stats()

        return {
            "queue_sizes": queue_sizes,
            "global_stats": stats,
            "disciplines": VALID_DISCIPLINES,
            "running": self._running,
        }

    async def run_scheduler_loop(self, interval_hours: float = 1.0) -> None:
        """Continuously check and regenerate tasks if needed (for long-running operation)."""
        self._running = True

        while self._running:
            # Check if any discipline queue is nearly empty
            queue_sizes = await self._task_manager.get_all_queue_sizes()
            for discipline in VALID_DISCIPLINES:
                size = queue_sizes.get(discipline, 0)
                if size < 10:
                    logger.info(
                        "queue_low_replenish",
                        discipline=discipline,
                        size=size,
                    )
                    await self.generate_discipline_tasks(discipline)

            await asyncio.sleep(interval_hours * 3600)

    async def stop(self) -> None:
        self._running = False
        logger.info("scheduler_stopped")
